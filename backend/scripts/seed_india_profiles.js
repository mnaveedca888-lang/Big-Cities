async function main() {
  const existingCountry = await prisma.country.findUnique({ where: { code: 'IN' } });
  if (existingCountry) {
    await prisma.country.update({ where: { code: 'IN' }, data: { name: 'India', profile: countryProfile } });
  } else {
    await prisma.country.create({ data: { code: 'IN', name: 'India', profile: countryProfile } });
  }

  for (const city of [...cityProfiles, ...additionalCityProfiles]) {
    const existing = await prisma.city.findUnique({ where: { slug: city.slug } });
    if (existing) {
      await prisma.city.update({ where: { slug: city.slug }, data: { profile: city.profile } });
    } else {
      await prisma.city.create({ data: { slug: city.slug, name: city.name, countryCode: 'IN', profile: city.profile } });
    }
  }

  const allIndianCities = await prisma.city.findMany({ where: { countryCode: 'IN' }, select: { slug: true, name: true, profile: true } });
  for (const city of allIndianCities) {
    const hasProfile = city.profile && typeof city.profile === 'object' && Object.keys(city.profile).length > 0;
    if (!hasProfile) {
      await prisma.city.update({ where: { slug: city.slug }, data: { profile: createGenericIndiaCityProfile(city.name) } });
    }
  }

  console.log('India country and city profiles seeded/updated. All Indian cities now have profiles.');
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
