async function updateCityData() {
  try {
    console.log('Starting comprehensive 45-field city data update...\n');

    for (const [citySlug, cityData] of Object.entries(AZERBAIJAN_CITIES_COMPLETE)) {
      // Convert arrays to proper format if needed
      const profileData = {
        ...cityData,
        // Ensure arrays and special fields are properly formatted
        unesco_sites: cityData.unesco_sites || [],
        major_landmarks: cityData.major_landmarks || [],
        museums: cityData.museums || [],
        parks: cityData.parks || [],
        festivals: cityData.festivals || [],
        major_industries: cityData.major_industries || [],
        traditional_food: Array.isArray(cityData.traditional_food) 
          ? cityData.traditional_food 
          : (typeof cityData.traditional_food === 'string' ? [cityData.traditional_food] : []),
        famous_people: Array.isArray(cityData.famous_people)
          ? cityData.famous_people
          : (typeof cityData.famous_people === 'string' ? [cityData.famous_people] : []),
        interesting_facts: Array.isArray(cityData.interesting_facts)
          ? cityData.interesting_facts
          : (typeof cityData.interesting_facts === 'string' ? [cityData.interesting_facts] : []),
      };

      const city = await prisma.city.update({
        where: { slug: citySlug },
        data: {
          profile: profileData
        }
      });

      console.log(`✓ Updated ${city.name} with 45-field complete data`);
    }

    console.log('\n✅ All cities updated with comprehensive 45-field data!');
  } catch (error) {
    console.error('Error updating city data:', error);
    process.exit(1);
  } finally {
    await prisma.$disconnect();
  }
}

