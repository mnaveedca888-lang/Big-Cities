async function main() {
  const existingCountry = await prisma.country.findUnique({ where: { code: 'AF' } });
  if (existingCountry) {
    await prisma.country.update({ where: { code: 'AF' }, data: { name: 'Afghanistan', profile: countryProfile } });
  } else {
    await prisma.country.create({ data: { code: 'AF', name: 'Afghanistan', profile: countryProfile } });
  }

  for (const city of cityProfiles) {
    const existing = await prisma.city.findUnique({ where: { slug: city.slug } });
    if (existing) {
      await prisma.city.update({ where: { slug: city.slug }, data: { profile: city.profile } });
    } else {
      await prisma.city.create({ data: { slug: city.slug, name: city.name, countryCode: 'AF', profile: city.profile } });
    }
  }

  console.log('Afghanistan country and city profiles seeded/updated.');
}

main()
  .catch((error) => {
    console.error(error);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
